    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
         try 
         {
            String cod = txtCodigo.getText().trim();
            String desc = txtDescripcion.getText().trim();
            double precio = Double.parseDouble(txtPrecio.getText().trim());
            int tiempo = Integer.parseInt(txtTiempo.getText().trim());
            
            modelo.Servicio s = new modelo.Servicio(cod, desc, precio, tiempo);
            controlador.registrarServicio(s);
            JOptionPane.showMessageDialog(this, "Servicio guardado");
            actualizarTabla();
            txtCodigo.setText(""); txtDescripcion.setText(""); txtPrecio.setText(""); txtTiempo.setText("");
        } catch (Exception e) 
        {
            JOptionPane.showMessageDialog(this, "Verifique los datos (el precio y tiempo deben ser numeros)");
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

