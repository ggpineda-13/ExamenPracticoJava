    private void actualizarTabla() 
    {
        modeloTabla.setRowCount(0);
        for (modelo.Servicio s : controlador.obtenerServicios()) 
        {
            modeloTabla.addRow(new Object[]{s.getCodigo(), s.getDescripcion(), s.getPrecioBase(), s.getTiempoEstimado()});
        }
    }

