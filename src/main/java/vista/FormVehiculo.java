    private void cargarClientesEnCombo() 
    {
        cmbPropietario.removeAllItems();
        for (Cliente c : controlador.obtenerClientes()) 
        {
            cmbPropietario.addItem(c);
        }
    }

    private void actualizarTabla() 
    {
        modeloTabla.setRowCount(0);
        for (Vehiculo v : controlador.obtenerVehiculos()) 
        {
            Object[] fila = {v.getPlaca(), v.getMarca(), v.getModelo(), v.getAnio(), v.getColor(), v.getPropietario().getNombre()};
            modeloTabla.addRow(fila);
        }
    }

