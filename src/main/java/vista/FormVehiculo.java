    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        int fila = tablaVehiculos.getSelectedRow();
        
        if (fila == -1) 
        {
            javax.swing.JOptionPane.showMessageDialog(this, "Seleccione un vehiculo de la tabla para eliminar.");
            return;
        }

        // Obtenemos la placa de la columna 0
        String placa = tablaVehiculos.getValueAt(fila, 0).toString();

        int confirmacion = javax.swing.JOptionPane.showConfirmDialog(this, 
                "¿Seguro que desea eliminar el vehiculo con placa " + placa + "?", 
                "Confirmar", javax.swing.JOptionPane.YES_NO_OPTION);

        if (confirmacion == javax.swing.JOptionPane.YES_OPTION) 
        {
            controlador.eliminarVehiculo(placa);
            javax.swing.JOptionPane.showMessageDialog(this, "Vehiculo eliminado");
            actualizarTabla(); // Refresca la tabla
            limpiarCampos();
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

