     private void limpiarCampos() 
     {
        txtPlaca.setText("");
        txtMarca.setText("");
        txtModelo.setText("");
        txtAnio.setText("");
        txtColor.setText("");
        if(cmbPropietario.getItemCount() > 0) cmbPropietario.setSelectedIndex(0);
    }
    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        String placa = txtPlaca.getText().trim();
        String marca = txtMarca.getText().trim();
        String modelo = txtModelo.getText().trim();
        String color = txtColor.getText().trim();
        String anioStr = txtAnio.getText().trim();

        // Validaciones
        if (placa.isEmpty() || marca.isEmpty() || anioStr.isEmpty()) 
        {
            JOptionPane.showMessageDialog(this, "Placa, marca y año son obligatorios", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (cmbPropietario.getItemCount() == 0) 
        {
            JOptionPane.showMessageDialog(this, "Debe registrar un cliente primero", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try 
        {
            int anio = Integer.parseInt(anioStr);
            Cliente propietario = (Cliente) cmbPropietario.getSelectedItem();
            
            // Creamos el vehiculo
            Vehiculo nuevo = new Vehiculo(placa, marca, modelo, anio, color, propietario);
            
            // Lo guardamos en el controlador
            if (controlador.registrarVehiculo(nuevo)) 
            {
                JOptionPane.showMessageDialog(this, "Vehiculo registrado con exito");
                actualizarTabla();
                limpiarCampos();
            } else {
                JOptionPane.showMessageDialog(this, "La placa ya existe", "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (NumberFormatException e) 
        {
            JOptionPane.showMessageDialog(this, "El año debe ser un numero", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

