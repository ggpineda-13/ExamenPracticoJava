    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
         // 1. Verificamos que el usuario haya seleccionado una fila
        int filaSeleccionada = tablaClientes.getSelectedRow();
        
        if (filaSeleccionada == -1) 
        {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, seleccione un cliente de la tabla para eliminar.");
            return;
        }

        // 2. Obtenemos el codigo del cliente de la fila seleccionada (columna 0)
        String codigo = tablaClientes.getValueAt(filaSeleccionada, 0).toString();
        String nombre = tablaClientes.getValueAt(filaSeleccionada, 1).toString();

        // 3. Confirmamos la eliminación
        int confirmacion = javax.swing.JOptionPane.showConfirmDialog(this, 
                "¿Está seguro que desea eliminar al cliente: " + nombre + "?", 
                "Confirmar Eliminacion", javax.swing.JOptionPane.YES_NO_OPTION);
        
        if (confirmacion == javax.swing.JOptionPane.YES_OPTION) 
        {
            // Llamamos al controlador para que lo elimine de la memoria (y lo guarde en el Stack)
            controlador.eliminarCliente(codigo); 
            
            javax.swing.JOptionPane.showMessageDialog(this, "Cliente eliminado correctamente.");
            actualizarTabla(); // Refrescamos la tabla
            limpiarCampos();   // Limpiamos las cajas de texto
        }
    }//GEN-LAST:event_btnEliminarActionPerformed
