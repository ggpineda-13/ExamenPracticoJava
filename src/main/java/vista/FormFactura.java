    private void btnCargarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargarActionPerformed
        // TODO add your handling code here:
        ordenSeleccionada = (OrdenTrabajo) cmbOrdenes.getSelectedItem();
        if (ordenSeleccionada != null) {
            // 1. Calculamos los montos
            Factura f = new Factura("TMP", ordenSeleccionada, 15.0);
            lblSubtotal.setText("Subtotal: Lps." + f.getSubtotal());
            lblImpuesto.setText("Impuesto (15%): Lps." + f.getImpuesto());
            lblTotal.setText("Total a Pagar: $" + f.getTotal());
            
            // 2. Armamos el texto de la factura
            StringBuilder detalle = new StringBuilder();
            
            detalle.append("========================================\n");
            detalle.append("       AUTOTECH SOLUTIONS - FACTURA     \n");
            detalle.append("========================================\n\n");
            
            // Datos del cliente y orden
            detalle.append("Orden No: ").append(ordenSeleccionada.getNumeroOrden()).append("\n");
            detalle.append("Fecha: ").append(ordenSeleccionada.getFecha()).append("\n");
            detalle.append("Cliente: ").append(ordenSeleccionada.getCliente().getNombre()).append("\n");
            detalle.append("Mecanico: ").append(ordenSeleccionada.getMecanico()).append("\n");
            detalle.append("----------------------------------------\n\n");
            
            // Servicios
            detalle.append("SERVICIOS REALIZADOS:\n");
            if(ordenSeleccionada.getServicios().isEmpty()){
                detalle.append(" - Ninguno\n");
            } else {
                for (Servicio s : ordenSeleccionada.getServicios()) {
                    detalle.append(" - ").append(s.getDescripcion()).append(": Lps.").append(s.getPrecioBase()).append("\n");
                }
            }
            
            // Repuestos
            detalle.append("\nREPUESTOS UTILIZADOS:\n");
            if(ordenSeleccionada.getRepuestos().isEmpty()){
                detalle.append(" - Ninguno\n");
            } else {
                for (Repuesto r : ordenSeleccionada.getRepuestos()) {
                    detalle.append(" - ").append(r.getNombre()).append(": Lps.").append(r.getPrecioUnitario()).append("\n");
                }
            }
            
            detalle.append("\n========================================\n");
            
            // 3. Lo mostramos en el TextArea
            txtDetalleFactura.setText(detalle.toString());
        }
    }//GEN-LAST:event_btnCargarActionPerformed

    private void btnPagarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPagarActionPerformed
        // TODO add your handling code here:
        //--- BOTON PAGAR (AQUI USAMOS LAS EXCEPCIONES) ---

         if (ordenSeleccionada == null) 
         {
            JOptionPane.showMessageDialog(this, "Primero cargue una orden");
            return;
        }

        try 
        {
            double efectivo = Double.parseDouble(txtEfectivo.getText().trim());
            
            // Llamamos al controlador para facturar. Si el dinero no alcanza o no hay stock, lanzará excepciones.
            Factura f = controlador.generarFactura("F-" + ordenSeleccionada.getNumeroOrden(), ordenSeleccionada, 15.0, efectivo);
            
            lblCambio.setText("Cambio: Lps." + f.getCambio());
            JOptionPane.showMessageDialog(this, "¡Pago exitoso! Cambio: Lps." + f.getCambio());
            
            // Limpiamos la ventana porque la orden ya se facturó
            limpiarEtiquetas();
            cmbOrdenes.removeItem(ordenSeleccionada);
            ordenSeleccionada = null;
            txtEfectivo.setText("");
            
        } catch (NumberFormatException e) 
        {
            JOptionPane.showMessageDialog(this, "Ingrese un monto en efectivo valido", "Error", JOptionPane.ERROR_MESSAGE);
        } catch (PagoInsuficienteException e) 
        {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Pago Insuficiente", JOptionPane.ERROR_MESSAGE);
        } catch (StockInsuficienteException e) 
        {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Sin Stock", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnPagarActionPerformed

