    private void actualizarTabla() 
    {
        modeloTabla.setRowCount(0);
        for (modelo.Repuesto r : controlador.obtenerRepuestos()) 
        {
            modeloTabla.addRow(new Object[]{r.getCodigo(), r.getNombre(), r.getCantidad(), r.getPrecioUnitario(), r.getStockMinimo()});
        }
    }
    

