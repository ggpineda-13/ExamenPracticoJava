    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        int fila = tablaRepuestos.getSelectedRow();
        
        if (fila == -1) 
        {
            javax.swing.JOptionPane.showMessageDialog(this, "Seleccione un repuesto de la tabla para eliminar.");
            return;
        }

        // Obtenemos el codigo de la columna 0
        String codigo = tablaRepuestos.getValueAt(fila, 0).toString();

        int confirmacion = javax.swing.JOptionPane.showConfirmDialog(this, 
                "¿Seguro que desea eliminar el repuesto con codigo " + codigo + "?", 
                "Confirmar", javax.swing.JOptionPane.YES_NO_OPTION);

        if (confirmacion == javax.swing.JOptionPane.YES_OPTION) 
        {
            controlador.eliminarRepuesto(codigo);
            javax.swing.JOptionPane.showMessageDialog(this, "Repuesto eliminado");
            actualizarTabla(); // Refresca la tabla
            limpiarCampos();
        }
    }//GEN-LAST:event_btnEliminarActionPerformed
    
