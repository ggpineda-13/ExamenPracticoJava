    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
         try 
         {
            String cod = txtCodigo.getText().trim();
            String nom = txtNombre.getText().trim();
            int cant = Integer.parseInt(txtCantidad.getText().trim());
            double precio = Double.parseDouble(txtPrecio.getText().trim());
            int min = Integer.parseInt(txtMinimo.getText().trim());
            
            // Creamos el objeto y lo guardamos en el controlador
            Repuesto r = new Repuesto(cod, nom, cant, precio, min);
            controlador.registrarRepuesto(r);
            
            JOptionPane.showMessageDialog(this, "Repuesto guardado con exito");
            actualizarTabla();            
        } catch (NumberFormatException e) 
        {
            JOptionPane.showMessageDialog(this, "Verifique los datos. Las cantidades y precios deben ser numeros.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

